import Foundation

/// Plans removing `target`, or records why not: it is kept, or it or `container` is in use.
func planPath(_ category: Category, _ target: String, reason: String, cfg: Config, guards: Guards,
              container: String? = nil, skips: inout [Skip]) -> Action? {
    if cfg.isKept(target) {
        skips.append(Skip(category: category, target: target, reason: "kept", kept: true, bytes: FS.allocatedSize(target)))
        return nil
    }
    if let veto = guards.veto(target) ?? container.flatMap(guards.veto) {
        skips.append(Skip(category: category, target: target, reason: "\(reason), but \(veto)"))
        return nil
    }
    return Action(category: category, target: target, reason: reason, bytes: FS.allocatedSize(target), status: .planned)
}

func removePath(_ a: Action) -> Action {
    var a = a
    do {
        try FS.remove(a.target)
        a.status = .removed
    } catch {
        a.status = .failed
        a.error = "\(error)"
    }
    return a
}

func days(_ from: Date, _ to: Date) -> Int { Int(to.timeIntervalSince(from) / 86400) }

enum TrashJanitor {
    /// Moving an item into the Trash renames it, which sets its ctime, so that is when it
    /// was trashed. A later chmod or xattr change sets it too, which only delays removal.
    static func plan(_ cfg: Config, guards: Guards, now: Date, skips: inout [Skip], issues: inout [Issue]) -> [Action] {
        let names: [String]
        do {
            names = try FileManager.default.contentsOfDirectory(atPath: cfg.trashDir)
        } catch {
            if FS.exists(cfg.trashDir) {
                issues.append(Issue(.trash, "cannot read \(cfg.trashDir); give janitor Full Disk Access in "
                                    + "System Settings > Privacy & Security"))
            }
            return []
        }
        let cutoff = now.addingTimeInterval(-cfg.trashIdleDays * 86400)
        return names.sorted().compactMap { name -> Action? in
            let path = cfg.trashDir + "/" + name
            guard name != ".DS_Store", let st = FS.lstatInfo(path), FS.ctime(st) < cutoff else { return nil }
            return planPath(.trash, path, reason: "in the Trash for \(days(FS.ctime(st), now)) days",
                            cfg: cfg, guards: guards, skips: &skips)
        }
    }
}

enum CacheJanitor {
    static var defaultRoots: [String] {
        let home = Paths.home.path
        var roots = [
            "Library/Caches", "Library/Developer/Xcode/DerivedData",
            "Library/Developer/Xcode/iOS DeviceSupport", "Library/Developer/Xcode/watchOS DeviceSupport",
            "Library/Developer/Xcode/tvOS DeviceSupport", "Library/Developer/CoreSimulator/Caches",
            "Library/pnpm/store", ".gradle/caches", ".gradle/wrapper/dists", ".gradle/daemon",
            ".npm/_npx", ".cache", ".pub-cache/hosted/pub.dev", ".bun/install/cache", ".yarn/berry/cache",
            ".android/cache",
        ].map { home + "/" + $0 }
        // The per-user cache folder under /var/folders.
        var buf = [CChar](repeating: 0, count: Int(PATH_MAX))
        if confstr(_CS_DARWIN_USER_CACHE_DIR, &buf, buf.count) > 0 {
            roots.append(FS.normalize(String(cString: buf)))
        }
        return roots
    }

    /// Each entry directly in a root goes once nothing under it was written or read for
    /// `cacheIdleDays`. macOS's own caches are left to macOS.
    static func plan(_ cfg: Config, guards: Guards, now: Date, skips: inout [Skip]) -> [Action] {
        let cutoff = now.addingTimeInterval(-cfg.cacheIdleDays * 86400)
        var actions: [Action] = []
        for root in cfg.cacheRoots.map(FS.canonical) {
            for name in ((try? FileManager.default.contentsOfDirectory(atPath: root)) ?? []).sorted()
            where name != ".DS_Store" && !name.hasPrefix("com.apple.") {
                let path = root + "/" + name
                guard !FS.isSymlink(path), let used = FS.lastUsed(path, newerThan: cutoff), used <= cutoff else { continue }
                if let a = planPath(.cache, path, reason: "unused for \(days(used, now)) days",
                                    cfg: cfg, guards: guards, skips: &skips) { actions.append(a) }
            }
        }
        return actions
    }
}

/// One walk of the search root, finding build output and large files.
struct HomeScan {
    /// Build or install output, and the project it belongs to.
    var artifacts: [(path: String, project: String)] = []
    var largeFiles: [String] = []

    /// Regenerated by a build or install, by name, and an entry beside one that shows
    /// it is that ("*.ext" matches any name with that extension).
    static let artifactMarkers: [String: [String]] = [
        "node_modules": ["package.json"],
        ".next": ["package.json"],
        "Pods": ["Podfile"],
        "build": ["build.gradle", "build.gradle.kts", "*.xcodeproj", "*.xcworkspace"],
        ".gradle": ["build.gradle", "build.gradle.kts", "settings.gradle", "settings.gradle.kts"],
        ".cxx": ["build.gradle", "build.gradle.kts"],
        "target": ["Cargo.toml"],
        ".build": ["Package.swift"],
    ]

    /// Disk images belong to an emulator or VM, which an idle stretch does not retire.
    static let diskImageExtensions: Set<String> = ["img", "qcow2", "raw", "ext4", "vmdk", "vdi", "vhdx", "iso"]

    static func isArtifact(_ name: String, in dir: String) -> Bool {
        guard let markers = artifactMarkers[name] else { return false }
        let entries = (try? FileManager.default.contentsOfDirectory(atPath: dir)) ?? []
        return markers.contains { m in
            m.hasPrefix("*.") ? entries.contains { $0.hasSuffix(m.dropFirst()) } : entries.contains(m)
        }
    }

    /// Never descends into `.git`, an artifact, a mount or anything in `skipping`. Large
    /// files are looked for only outside hidden folders and packages (apps, libraries).
    static func scan(_ root: String, skipping: Set<String>, largeFileBytes: Int64?) -> HomeScan {
        var result = HomeScan()
        var stack: [(path: String, project: String?, visible: Bool)] = [(root, nil, true)]
        let skip = skipping.union(FS.mountPoints())
        while let (dir, outer, visible) = stack.popLast() {
            guard let names = try? FileManager.default.contentsOfDirectory(atPath: dir) else { continue }
            let project = names.contains(".git") ? dir : outer
            for name in names where name != ".git" {
                let path = dir + "/" + name
                guard !skip.contains(path), let st = FS.lstatInfo(path) else { continue }
                switch st.st_mode & S_IFMT {
                case S_IFDIR:
                    if isArtifact(name, in: dir) {
                        result.artifacts.append((path, project ?? dir))
                        continue
                    }
                    let ext = (name as NSString).pathExtension
                    let package = !ext.isEmpty && ((try? URL(fileURLWithPath: path).resourceValues(forKeys: [.isPackageKey]))?.isPackage ?? false)
                    stack.append((path, project, visible && !name.hasPrefix(".") && !package))
                case S_IFREG:
                    if visible, let min = largeFileBytes, Int64(st.st_size) >= min,
                       !diskImageExtensions.contains((name as NSString).pathExtension.lowercased()) {
                        result.largeFiles.append(path)
                    }
                default:
                    break
                }
            }
        }
        return result
    }
}

enum BuildJanitor {
    /// The newest file in `project` outside its build output and `.git`, plus its git HEAD
    /// and index. Directory times are ignored: removing output changes them.
    static func newestSource(_ project: String, newerThan cutoff: Date) -> Date {
        var newest = Date.distantPast
        for f in [".git/HEAD", ".git/index"] {
            if let st = FS.lstatInfo(project + "/" + f) { newest = max(newest, FS.mtime(st)) }
        }
        if let gitdir = WorktreeJanitor.gitdir(of: project) {
            for f in ["HEAD", "index"] {
                if let st = FS.lstatInfo(gitdir + "/" + f) { newest = max(newest, FS.mtime(st)) }
            }
        }
        if newest > cutoff { return newest }
        FS.walk(project) { _, name, st, stop in
            if st.st_mode & S_IFMT == S_IFDIR { return name != ".git" && HomeScan.artifactMarkers[name] == nil }
            newest = max(newest, FS.mtime(st))
            if newest > cutoff { stop = true }
            return true
        }
        return newest
    }

    /// Output goes once neither it nor its project changed for `buildIdleDays`.
    /// `owner` names what else decides about a path (another rule), or nil.
    static func plan(_ cfg: Config, guards: Guards, now: Date, scan: HomeScan,
                     owner: (_ path: String) -> String?, skips: inout [Skip]) -> [Action] {
        let cutoff = now.addingTimeInterval(-cfg.buildIdleDays * 86400)
        var projectNewest: [String: Date] = [:]
        var actions: [Action] = []
        for (path, project) in scan.artifacts.sorted(by: { $0.path < $1.path }) {
            guard owner(path) == nil else { continue }
            let source = projectNewest[project] ?? newestSource(project, newerThan: cutoff)
            projectNewest[project] = source
            guard source <= cutoff, let output = FS.newestMTime(path, newerThan: cutoff), output <= cutoff else { continue }
            let reason = "\((project as NSString).lastPathComponent) untouched for \(days(max(source, output), now)) days"
            if let a = planPath(.build, path, reason: reason, cfg: cfg, guards: guards, container: project, skips: &skips) {
                actions.append(a)
            }
        }
        return actions
    }
}

enum LargeFileJanitor {
    static func plan(_ cfg: Config, guards: Guards, now: Date, scan: HomeScan, skips: inout [Skip]) -> [Action] {
        let cutoff = now.addingTimeInterval(-cfg.largeFileIdleDays * 86400)
        return scan.largeFiles.sorted().compactMap { path -> Action? in
            guard let used = FS.lastUsed(path), used <= cutoff else { return nil }
            return planPath(.largeFile, path, reason: "untouched for \(days(used, now)) days; goes to the Trash",
                            cfg: cfg, guards: guards, skips: &skips)
        }
    }

    /// To the Trash, from where `TrashJanitor` removes it after `trashIdleDays`.
    static func execute(_ a: Action) -> Action {
        var a = a
        do {
            try Safety.check(a.target)
            try FileManager.default.trashItem(at: URL(fileURLWithPath: a.target), resultingItemURL: nil)
            a.status = .removed
        } catch {
            a.status = .failed
            a.error = "\(error)"
        }
        return a
    }
}
